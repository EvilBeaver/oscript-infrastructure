-- Разовый перенос данных пакетов из старого хаба (opm-hub) в OpenHub.
-- Запускается в базе сервиса openhub_db после того, как run.sh залил выгрузку
-- в таблицу opm_import (см. stage-openhub.sql).
--
-- Зеркалирование забирает у старого хаба только имена, версии и сами .ospx: протокол
-- list.txt дат не отдаёт, поэтому у всех перенесённых версий «Опубликована» — момент
-- прогона зеркала. Этот скрипт возвращает им настоящие даты из базы старого хаба.
--
-- Имена таблиц и колонок — БЕЗ КАВЫЧЕК и ровно так, как их писала библиотека entity
-- в своём CREATE TABLE: PostgreSQL свернёт их здесь по тем же правилам, по каким свернул
-- при создании, какой бы ни была кодировка базы.
--
-- Параметры psql:
--   -v apply=true|false         фиксировать транзакцию или откатить (прогон вхолостую)
--   -v pool='' | '<имя>' | '*'  где лежат зеркалированные пакеты: пусто — пул по
--                               умолчанию, '*' — все пулы
--   -v touch_changed=true|false двигать ли назад «Изменена» вслед за «Опубликована»
--
-- Все правки идут только назад по времени: строку, которая в OpenHub уже старше
-- привезённой даты, скрипт не трогает — собственные публикации хаба переносом не теряются.

\set ON_ERROR_STOP on

BEGIN;

-- ── Подготовка ───────────────────────────────────────────────────────────────

CREATE TEMP TABLE пулы_цели ON COMMIT DROP AS
SELECT Идентификатор AS ид, Имя AS имя
FROM Пулы
WHERE :'pool' = '*'
   OR (:'pool' = '' AND ПоУмолчанию = true)
   OR Имя = :'pool';

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM пулы_цели) THEN
        RAISE EXCEPTION 'Целевой пул не найден: проверьте --pool (пусто — пул по умолчанию, * — все пулы)';
    END IF;
END $$;

-- Пакет старого хаба одной строкой. Дата создания пакета там проставлялась текущим
-- моментом при первой публикации, а разовая миграция 2019 года выставила её всем сразу,
-- поэтому берём минимум из неё и даты самой ранней версии.
CREATE TEMP TABLE пакеты_opm ON COMMIT DROP AS
SELECT имя_пакета,
       LEAST(
           COALESCE(min(пакет_создан)   FILTER (WHERE пакет_создан   > TIMESTAMP '1970-01-01'), TIMESTAMP 'infinity'),
           COALESCE(min(версия_создана) FILTER (WHERE версия_создана > TIMESTAMP '1970-01-01'), TIMESTAMP 'infinity')
       )                                AS создан,
       max(описание)                    AS описание,
       max(ключевые_слова)              AS ключевые_слова,
       max(ссылка_на_проект)            AS ссылка_на_проект,
       max(автор)                       AS автор,
       max(автор_почта)                 AS автор_почта,
       count(*)                         AS версий
FROM opm_import
GROUP BY имя_пакета;

-- Одна строка на имя+версию: если в старой базе оказались дубли, берём самую раннюю.
CREATE TEMP TABLE версии_opm ON COMMIT DROP AS
SELECT DISTINCT ON (имя_пакета, версия)
       имя_пакета,
       версия,
       версия_создана,
       GREATEST(версия_обновлена, версия_создана) AS изменена
FROM opm_import
WHERE версия_создана > TIMESTAMP '1970-01-01'
ORDER BY имя_пакета, версия, версия_создана;

-- Пакеты OpenHub, которым есть что переносить.
CREATE TEMP TABLE соответствие ON COMMIT DROP AS
SELECT p.Идентификатор AS пакет_ид, p.ИмяНижнийРегистр AS имя
FROM Пакеты p
JOIN пулы_цели ц ON ц.ид = p.ПулИдентификатор
JOIN пакеты_opm o ON o.имя_пакета = p.ИмяНижнийРегистр;

\echo ''
\echo '== Что нашлось =='
SELECT (SELECT string_agg(имя, ', ' ORDER BY имя) FROM пулы_цели) AS "целевые пулы",
       (SELECT count(*) FROM пакеты_opm)                          AS "пакетов в старом хабе",
       (SELECT count(*) FROM соответствие)                        AS "из них есть в OpenHub",
       (SELECT count(*) FROM версии_opm)                          AS "версий в старом хабе";

-- ── 1. Даты публикации версий ────────────────────────────────────────────────

\echo ''
\echo '== 1. Опубликована у версий =='
UPDATE ВерсииПакетов в
SET Опубликована = o.версия_создана
FROM версии_opm o
JOIN соответствие с ON с.имя = o.имя_пакета
WHERE в.ПакетИдентификатор = с.пакет_ид
  AND в.Версия = o.версия
  AND (в.Опубликована IS NULL
       OR в.Опубликована <= TIMESTAMP '1970-01-01'
       OR в.Опубликована > o.версия_создана);

-- ── 2. Момент последнего изменения записи ────────────────────────────────────
-- «Изменена» — курсор среза изменений для чужих зеркал OpenHub: сдвиг назад прячет
-- эти версии от тех, кто ещё не синхронизировался. По умолчанию выключено.

\echo ''
\echo '== 2. Изменена у версий =='
\if :touch_changed
UPDATE ВерсииПакетов в
SET Изменена = o.изменена
FROM версии_opm o
JOIN соответствие с ON с.имя = o.имя_пакета
WHERE в.ПакетИдентификатор = с.пакет_ид
  AND в.Версия = o.версия
  AND o.изменена > TIMESTAMP '1970-01-01'
  AND (в.Изменена IS NULL
       OR в.Изменена <= TIMESTAMP '1970-01-01'
       OR в.Изменена > o.изменена);
\else
\echo '(пропущено: запустите run.sh --touch-changed, если нужно)'
\endif

-- ── 3. Дата создания пакета ──────────────────────────────────────────────────

\echo ''
\echo '== 3. Создан у пакетов =='
UPDATE Пакеты п
SET Создан = o.создан
FROM пакеты_opm o
JOIN соответствие с ON с.имя = o.имя_пакета
WHERE п.Идентификатор = с.пакет_ид
  AND o.создан < TIMESTAMP 'infinity'
  AND (п.Создан IS NULL
       OR п.Создан <= TIMESTAMP '1970-01-01'
       OR п.Создан > o.создан);

-- ── 4. Отметка последней публикации ──────────────────────────────────────────
-- Считается заново по действующим версиям — тем же правилом, что и в СервисВерсий:
-- отозванные версии свежесть пакета не задают.

\echo ''
\echo '== 4. ПоследняяПубликация у пакетов =='
UPDATE Пакеты п
SET ПоследняяПубликация = COALESCE(м.момент, TIMESTAMP '0001-01-01')
FROM соответствие с
LEFT JOIN LATERAL (
    SELECT max(в.Опубликована) AS момент
    FROM ВерсииПакетов в
    WHERE в.ПакетИдентификатор = с.пакет_ид
      AND в.Отозвана IS NOT TRUE
) м ON true
WHERE п.Идентификатор = с.пакет_ид
  AND п.ПоследняяПубликация IS DISTINCT FROM COALESCE(м.момент, TIMESTAMP '0001-01-01');

-- ── 5. Описание, ключевые слова, адрес репозитория ───────────────────────────
-- В OpenHub эти поля приезжают из манифеста внутри .ospx и обычно уже заполнены.
-- Дописываем только пустые: у старого хаба описание и ссылка на проект могли быть
-- добавлены руками или собраны по GitHub, и в манифесте их нет.

\echo ''
\echo '== 5. Описание у пакетов (только пустые) =='
UPDATE Пакеты п
SET Описание = o.описание
FROM пакеты_opm o
JOIN соответствие с ON с.имя = o.имя_пакета
WHERE п.Идентификатор = с.пакет_ид
  AND o.описание <> ''
  AND COALESCE(п.Описание, '') = '';

\echo '== 5. КлючевыеСлова у пакетов (только пустые) =='
UPDATE Пакеты п
SET КлючевыеСлова = o.ключевые_слова
FROM пакеты_opm o
JOIN соответствие с ON с.имя = o.имя_пакета
WHERE п.Идентификатор = с.пакет_ид
  AND o.ключевые_слова <> ''
  AND COALESCE(п.КлючевыеСлова, '') = '';

\echo '== 5. АдресРепозитория у пакетов (только пустые) =='
UPDATE Пакеты п
SET АдресРепозитория = o.ссылка_на_проект
FROM пакеты_opm o
JOIN соответствие с ON с.имя = o.имя_пакета
WHERE п.Идентификатор = с.пакет_ид
  AND o.ссылка_на_проект ~* '^https?://'
  AND COALESCE(п.АдресРепозитория, '') = '';

-- ── Что осталось за переносом ────────────────────────────────────────────────

\echo ''
\echo '== Версии старого хаба, которых нет в OpenHub (топ-20 пакетов) =='
SELECT o.имя_пакета AS "пакет", count(*) AS "версий не найдено"
FROM версии_opm o
LEFT JOIN соответствие с ON с.имя = o.имя_пакета
LEFT JOIN ВерсииПакетов в
       ON в.ПакетИдентификатор = с.пакет_ид AND в.Версия = o.версия
WHERE в.Идентификатор IS NULL
GROUP BY 1
ORDER BY 2 DESC, 1
LIMIT 20;

\echo ''
\echo '== Авторы старого хаба и похожие учётки OpenHub (права переносятся руками) =='
SELECT o.автор                                   AS "автор в манифесте",
       NULLIF(o.автор_почта, '')                 AS "почта",
       count(*)                                  AS "пакетов",
       string_agg(DISTINCT п.Логин, ', ')        AS "похожие учётки OpenHub"
FROM пакеты_opm o
JOIN соответствие с ON с.имя = o.имя_пакета
LEFT JOIN Пользователи п
       ON lower(п.Логин) = lower(o.автор)
       OR (o.автор_почта <> '' AND lower(п.Email) = lower(o.автор_почта))
WHERE o.автор <> ''
GROUP BY 1, 2
ORDER BY 3 DESC, 1
LIMIT 30;

\echo ''
\echo '== Как стало: 10 самых свежих пакетов =='
SELECT п.Имя                  AS "пакет",
       п.Создан               AS "создан",
       п.ПоследняяПубликация  AS "последняя публикация"
FROM Пакеты п
JOIN соответствие с ON с.пакет_ид = п.Идентификатор
ORDER BY п.ПоследняяПубликация DESC
LIMIT 10;

-- ── Фиксация ─────────────────────────────────────────────────────────────────

\if :apply
DROP TABLE opm_import;
\echo ''
\echo '== Переносим: фиксирую транзакцию =='
COMMIT;
\else
\echo ''
\echo '== Прогон вхолостую: откатываю. Для записи — run.sh --apply =='
ROLLBACK;
\endif
